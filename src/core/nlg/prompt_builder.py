    @staticmethod
    def _build_quarterly_table(extra: dict) -> str:
        """Формирует таблицу последних 5 кварталов с QoQ-изменениями."""
        labels = extra.get("quarter_labels", [])
        self_vals = extra.get("self_values_fmt", extra.get("self_values", []))
        rest_vals = extra.get("rest_values_fmt", extra.get("rest_values", []))
        qoq_self = extra.get("qoq_self_fmt", extra.get("qoq_self", []))
        qoq_rest = extra.get("qoq_rest_fmt", extra.get("qoq_rest", []))

        n = len(labels)
        if n == 0:
            return "— Нет данных"

        # Берём последние 5 кварталов (или все, если их меньше 5)
        start = max(0, n - 5)
        rows = []
        for i in range(start, n):
            # Анонимизируем метки: К1, К2... чтобы LLM не ссылался на конкретные кварталы
            label = f"Квартал {i+1}"
            sv = self_vals[i] if i < len(self_vals) else "—"
            rv = rest_vals[i] if i < len(rest_vals) else "—"
            # QoQ для первого элемента в таблице показываем как прочерк
            if i == start:
                qs = "—"
                qr = "—"
            else:
                qi = i - 1
                qs = qoq_self[qi] if qi < len(qoq_self) else "—"
                qr = qoq_rest[qi] if qi < len(qoq_rest) else "—"
            rows.append(
                f"- {label}: банк {sv}, рынок {rv}, "
                f"изм. банка {qs}, изм. рынка {qr}"
            )
        return "\n".join(rows)

