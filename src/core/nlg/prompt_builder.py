    @staticmethod
    def _fmt(val: float) -> str:
        """Русский формат с двумя знаками после запятой: 0.269 → 0,27"""
        return f"{val:.2f}".replace(".", ",")

    @staticmethod
    def _format_style_example(examples: list) -> str:
        if not examples:
            return ""
        ex = examples[0]
        verdict = ex.get("verdict", "")
        if not verdict:
            return ""
        return (
            "ЭТАЛОННЫЙ ПРИМЕР (только стиль и структура предложений, "
            "не источник фактов — не переносить цифры из примера в ответ):\n"
            f'"{verdict}"'
        )