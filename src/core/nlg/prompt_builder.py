    def _build_loss_buckets(
        self, calculations: MetricCalculations, positive_examples: list
    ) -> tuple:
        system = DOMAIN_INSTRUCTIONS["loss_buckets"]
        ex = calculations.extra

        data_block = DATA_TEMPLATE_LOSS_BUCKETS.format(
            scenario_label=ex.get("scenario_label", "—"),
            total_deviation=ex.get("total_deviation", "—"),
            total_deviation_sentence=ex.get("total_deviation_sentence", "—"),
            max_bank_bucket=ex.get("max_bank_bucket", "—"),
            max_bank_pct=ex.get("max_bank_pct", 0),
            max_rest_bucket=ex.get("max_rest_bucket", "—"),
            min_bank_bucket=ex.get("min_bank_bucket", "—"),
            min_rest_bucket=ex.get("min_rest_bucket", "—"),
            max_buckets_match=ex.get("max_buckets_match", False),
            min_buckets_match=ex.get("min_buckets_match", False),
            buckets_match_sentence=ex.get("buckets_match_sentence", "—"),
            max_diff_bucket=ex.get("max_diff_bucket", "—"),
            max_diff_abs=ex.get("max_diff_abs", "—"),
            max_diff_sentence=ex.get("max_diff_sentence", "—"),
            any_diff_over_10=ex.get("any_diff_over_10", False),
            concentration_sentence=ex.get("concentration_sentence", ""),
            min_mismatch_sentence=ex.get("min_mismatch_sentence", ""),
        )

        scenario = ex.get("scenario_label", "расхождения")
        scenario_structure = self.LOSS_BUCKETS_STRUCTURE_TEMPLATES.get(
            scenario,
            self.LOSS_BUCKETS_STRUCTURE_TEMPLATES["расхождения"]  # fallback
        )

        # Намеренно НЕ передаём style_example — иначе LLM копирует эталон дословно.
        # Ключевые предложения уже заданы в data_block через поля «Готовое предложение о...».
        user_parts = [data_block, scenario_structure]
        user_parts.append(
            "Сформируйте аналитический вывод строго по СТРУКТУРЕ ДЛЯ ТЕКУЩЕГО СЦЕНАРИЯ. "
            "Все числа и факты из входных данных оставляйте точными — не менять. "
            "Метки бакетов (например «<20», «350+», «7000+») оставляйте точно как в данных — "
            "не переводить в «до 20», «от 350» и т.п. "
            "Слова в предложениях можно заменять простыми синонимами — без заумных или "
            "профессиональных терминов, только простые разговорные замены. "
            "Каждое предложение из структуры оставляйте отдельным — не объединяйте их. "
            "Эталонные примеры — только для понимания стиля, не копировать дословно. "
            "Можете добавить одно короткое предложение (не более 15 слов), если оно даёт "
            "конкретное аналитическое наблюдение по данным. Больше одного предложения не добавляйте."
        )
        return system, "\n\n".join(user_parts)

