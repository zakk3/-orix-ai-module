    def _build_dynamics(
        self, calculations: MetricCalculations, positive_examples: list
    ) -> tuple:
        system = DOMAIN_INSTRUCTIONS["direct_losses_dynamics"]
        ex = calculations.extra

        data_block = DATA_TEMPLATE_DYNAMICS.format(
            first_quarter=ex.get("first_quarter_serie", "—"),
            last_quarter=ex.get("last_quarter_serie", "—"),
            total_quarters=ex.get("total_quarters", "—"),
            bank_trend=ex.get("bank_trend_3q", "—"),
            market_trend=ex.get("market_trend_3q", "—"),
            divergence_label=ex.get("divergence_label", "—"),
            last_4q_factor=ex.get("last_4q_factor_fmt", "—"),
            last_4q_direction=ex.get("last_4q_direction", "—"),
            last_quarter_label=ex.get("last_quarter_label", "—"),
            last_q_factor=ex.get("last_q_factor_fmt", "—"),
            last_q_direction=ex.get("last_q_direction", "—"),
            consistent_above="да" if ex.get("consistent_above_market") else "нет",
            consistent_below="да" if ex.get("consistent_below_market") else "нет",
            size_class_sentence=ex.get("size_class_sentence") or "(не применимо)",
            # Поля для сценария «драматично отличаются»
            loss_level=ex.get("loss_level", "—"),
            high_loss_threshold_mln=ex.get("high_loss_threshold_mln", "—"),
            high_loss_count_last_4=ex.get("high_loss_count_last_4", "—"),
            volatility_level=ex.get("volatility_level", "—"),
            peak_quarter_label=ex.get("peak_quarter_label", "—"),
            peak_factor=ex.get("peak_factor_fmt", "—"),
            peak_direction=ex.get("peak_direction", "—"),
            mostly_position=ex.get("mostly_position_label", "—"),
        )

        # Выбираем сценарно-зависимый шаблон структуры по характеристике расхождения
        divergence = ex.get("divergence_label", "")
        scenario_structure = self.DYNAMICS_STRUCTURE_TEMPLATES.get(
            divergence,
            self.DYNAMICS_STRUCTURE_TEMPLATES["несколько отличаются"]  # fallback
        )

        user_parts = [data_block, scenario_structure]
        style = self._style_example(positive_examples)
        if style:
            user_parts.append(style)
        user_parts.append(NEGATIVE_EXAMPLE_DYNAMICS)
        user_parts.append(
            "Сформируйте аналитический вывод строго по СТРУКТУРЕ ДЛЯ ТЕКУЩЕГО СЦЕНАРИЯ. "
            "Не добавляйте предложения которых нет в шаблоне. "
            "Только факты из входных данных."
        )
        return system, "\n\n".join(user_parts)

    # ── Helpers ────────────────────────────────────────────────────────────

    @staticmethod
    def _fmt(val: float) -> str:
        # Русский формат с двумя знаками: 0.269 → 0,27
        return f"{val:.2f}".replace(".", ",")

    @staticmethod
    def _threshold_from_level(deviation_level: str) -> float:
        if "норме" in deviation_level:
            return 0.5
        elif "приближается" in deviation_level:
            return 0.8
        elif "превышает пороговый" in deviation_level:
            return 0.96
        return 0.96

    @staticmethod
    def _style_example(examples: list) -> str:
        if not examples:
            return ""
        verdict = examples[0].get("verdict", "")
        if not verdict:
            return ""
        return (
            "ЭТАЛОННЫЙ ПРИМЕР (только стиль и структура предложений, "
            "не источник фактов — не переносить цифры из примера в ответ):\n"
            f'"{verdict}"'
        )
