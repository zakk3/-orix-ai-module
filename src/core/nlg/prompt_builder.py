class PromptBuilder:

    def build(
        self,
        metric_type: str,
        calculations: MetricCalculations,
        positive_examples: list,
    ) -> tuple:
        # Роутинг по типу метрики
        if metric_type == "loss_share":
            return self._build_loss_share(calculations, positive_examples)
        elif metric_type == "direct_losses_dynamics":
            return self._build_dynamics(calculations, positive_examples)
        elif metric_type == "loss_buckets":
            return self._build_loss_buckets(calculations, positive_examples)
        elif metric_type == "recovery_level":
            return self._build_recovery_rate(calculations, positive_examples)
        elif metric_type == "concentration":
            return self._build_concentration(calculations, positive_examples)
        else:
            raise ValueError(f"Domain prompt для метрики '{metric_type}' не найден")

    # Метрика 1

    def _build_loss_share(
        self, calculations: MetricCalculations, positive_examples: list
    ) -> tuple:
        system = DOMAIN_INSTRUCTIONS["loss_share"]

        deviation_level = calculations.extra.get("deviation_level", "")
        magnitude_label = calculations.extra.get(
            "magnitude_label",
            "ниже среднего" if calculations.is_below_average else "выше среднего",
        )

        outlier_sentence = calculations.extra.get("outlier_sentence") or "—"

        data_block = DATA_TEMPLATE_LOSS_SHARE.format(
            period_display=calculations.extra.get("period_display", "—"),
            opening_sentence=calculations.extra.get("opening_sentence", "—"),
            median_sentence=calculations.extra.get("median_sentence", "—"),
            position_sentence=calculations.extra.get("position_sentence", "—"),
            outlier_sentence=outlier_sentence,
        )

        user_parts = [data_block]
        style = self._style_example(positive_examples)
        if style:
            user_parts.append(style)
        user_parts.append(NEGATIVE_EXAMPLE_LOSS_SHARE)
        user_parts.append(
            "Сформируйте аналитический вывод строго из готовых предложений (пп. 1–5). "
            "Один связный абзац. "
            "Ровно 3 предложения (4 если есть выброс). Ничего лишнего."
        )
        return system, "\n\n".join(user_parts)

